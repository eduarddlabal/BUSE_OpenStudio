def _scale_icon_rows(rows: list[str], target_h: int) -> list[str]:
    """Scale an 8-row base icon cleanly into target_h rows for fallback exterior icons."""
    w = max((len(r) for r in rows), default=1)
    if target_h <= 8:
        return (list(rows) + ["." * w] * target_h)[:target_h]
    top = 3 if target_h >= 16 else 2
    bottom = 2 if target_h >= 18 else 1
    inner_h = max(1, target_h - top - bottom)
    scale_x = 2 if target_h >= 16 else 1
    pad = "." * (w * scale_x)
    out = [pad] * top
    for y in range(inner_h):
        src_r = rows[min(len(rows) - 1, y * len(rows) // inner_h)]
        out.append("".join(ch * scale_x for ch in src_r.ljust(w, ".")))
    out.extend([pad] * bottom)
    return out[:target_h]


def exterior_icon_rows(name: str, height: int) -> list[str]:
    """Return a crisp pixel bitmap sized for exterior gBUSE0 font height."""
    h = max(8, int(height))
    if h <= 8:
        rows = ICONS[name]
    elif h <= 12:
        rows = ICONS_9.get(name) or (["." * len(ICONS[name][0])] + ICONS[name] + ["." * len(ICONS[name][0])])
    elif h <= 16:
        rows = ICONS_16.get(name) or _scale_icon_rows(ICONS[name], 16)
    else:
        rows = ICONS_19.get(name) or _scale_icon_rows(ICONS[name], 19)
    w = max((len(r) for r in rows), default=1)
    if len(rows) < h:
        rows = list(rows) + ["." * w] * (h - len(rows))
    return rows[:h]


def add_exterior_icons(fonts, replace: bool = True):
    """Inject exterior PID pictograms into every gBUSE0 text font (keeps original 0xAF, 0xF1-0xF4)."""
    from .fonts import Glyph
    font_list = fonts.fonts if hasattr(fonts, "fonts") else fonts.values()
    for f in font_list:
        if f.id >= ICON_FONT or not f.glyphs:
            continue
        if 0x41 not in f.glyphs and len(f.glyphs) < 20:
            continue
        ref = f.glyphs.get(0x41)
        cell_h = ref.height if ref is not None else max(g.height for g in f.glyphs.values())
        glyphs = dict(f.glyphs)
        for name in ICONS:
            code = ICON_CODES[name]
            if replace or code not in glyphs:
                rows = exterior_icon_rows(name, cell_h)
                old = glyphs.get(code)
                h = max(cell_h, old.height) if old is not None else cell_h   # keep the font's glyph height
                rows = rows + ["." * len(rows[0])] * (h - len(rows))
                glyphs[code] = Glyph.from_rows(code, rows, height=h)
        f.glyphs = dict(sorted(glyphs.items()))
    return fonts


