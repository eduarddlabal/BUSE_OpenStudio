G["ı"] = ["...", "...", "##.", ".#.", ".#.", ".#.", "###"]   # dotless i (base for í)

ACCENT_ROWS = {  # (upper row, lower row) relative to the letter centre c; "." = empty
    "acute": ({1}, {0}), "caron": ({-1, 1}, {0}), "ring": ({0}, {-1, 1}), "umlaut": ({-1, 1}, set()),
    "circ": ({0}, {-1, 1}),
}


def _grid(rows7: list[str]) -> list[str]:
    """7-row body -> 8-row grid (row 0 free for accents of capitals)."""
    return ["." * len(rows7[0])] + list(rows7)


def _accented(base: str, kind: str) -> list[str]:
    body = G[base]
    w = len(body[0])
    g = [list(r) for r in _grid(body)]
    c = w // 2
    if kind == "apos":                         # ď ť ľ Ľ: small tick right of the letter
        g = [r + ["."] for r in g]
        for y in (1, 2):
            g[y][w] = "#"
        return ["".join(r) for r in g]
    upper, lower = ACCENT_ROWS[kind]
    capital = base.isupper()
    if capital:                                # only row 0 above a capital
        for dx in ({0} if kind in ("ring", "circ") else upper):
            if 0 <= c + dx < w:
                g[0][c + dx] = "#"
    else:                                      # rows 1–2 are free above x-height letters
        for dx in upper:
            if 0 <= c + dx < w:
                g[1][c + dx] = "#"
        for dx in lower:
            if 0 <= c + dx < w:
                g[2][c + dx] = "#"
    return ["".join(r) for r in g]


def _all_glyphs() -> dict[str, list[str]]:
    out = {ch: _grid(rows) for ch, rows in G.items() if ch != "ı"}
    for ch, (base, kind) in ACCENTS.items():
        out[ch] = _accented(base, kind)
    return out


def _bold(rows: list[str]) -> list[str]:
    w = len(rows[0])
    out = []
    for r in rows:
        bits = [c == "#" for c in r] + [False]
        out.append("".join("#" if bits[x] or (x > 0 and bits[x - 1]) else "." for x in range(w + 1)))
    return out


def codetable() -> CodeTable:
    raw = bytearray(160)
    for i in range(160):
        code = 0x21 + i
        if code < 0x80:
            raw[i] = code
        elif code - 0x80 < len(KAMENICKY):
            try:
                raw[i] = KAMENICKY[code - 0x80].encode("cp1250")[0]
            except UnicodeEncodeError:
                raw[i] = 0
    return CodeTable(bytes(raw))


def panel_code(ch: str) -> int | None:
    if ch == " " or (" " < ch < "\x7f"):
        return ord(ch)
    i = KAMENICKY.find(ch)
    return 0x80 + i if i >= 0 else None


def builtin_fontset(thin_id: int = 0, bold_id: int = 3) -> FontSet:
    glyphs = _all_glyphs()
    fonts = []
    for fid, transform in ((thin_id, lambda r: r), (bold_id, _bold)):
        f = Font(fid)
        f.glyphs[0x20] = Glyph(0x20, 8, bytes(3))
        for ch in sorted(glyphs, key=lambda c: panel_code(c) or 999):
            code = panel_code(ch)
            if code is None or code == 0x20:
                continue
            f.glyphs[code] = Glyph.from_rows(code, transform(glyphs[ch]))
        fonts.append(f)
    return FontSet(fonts, codetable())
